"""Builds the English page en/index.html from the Czech index.html and i18n/en.json.

The Czech texts live in index.html (edit them there), the English ones in i18n/en.json, keyed by the elements'
data-i18n (plain text), data-i18n-html (with markup), data-i18n-aria (aria-label) and data-i18n-content (a meta
tag's content). Run after changing either:  python tools/build-en.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = 'https://tomandes.eu'

html = (ROOT / 'index.html').read_text(encoding='utf-8')
EN = json.loads((ROOT / 'i18n' / 'en.json').read_text(encoding='utf-8'))
used = set()


def escape_text(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def escape_attr(s):
    return escape_text(s).replace('"', '&quot;')


def replace_content(source, attr, value):
    """Replaces the inner HTML of each element carrying attr="key" (closing tag found by nesting depth)."""
    out, pos = [], 0
    pattern = re.compile(r'<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*\s' + attr + r'="([^"]+)"[^>]*>')
    for m in pattern.finditer(source):
        if m.start() < pos:
            continue
        tag, key = m.group(1), m.group(2)
        if key not in EN:
            sys.exit(f'No English text for {attr}="{key}"')
        used.add(key)
        depth, i = 1, m.end()
        token = re.compile(r'<(/?)' + tag + r'\b[^>]*>', re.I)
        while depth:
            t = token.search(source, i)
            if not t:
                sys.exit(f'Unclosed <{tag}> for {key}')
            depth += -1 if t.group(1) else 1
            i = t.end()
        close_start = t.start()
        out.append(source[pos:m.end()])
        out.append(value(EN[key]))
        pos = close_start
    out.append(source[pos:])
    return ''.join(out)


def replace_attribute(source, marker, target):
    """In each tag carrying marker="key", sets target="English"."""
    def fix(m):
        tag = m.group(0)
        key = re.search(marker + r'="([^"]+)"', tag).group(1)
        if key not in EN:
            sys.exit(f'No English text for {marker}="{key}"')
        used.add(key)
        return re.sub(r'\s' + target + r'="[^"]*"', f' {target}="{escape_attr(EN[key])}"', tag, count=1)
    return re.sub(r'<[^>]*\s' + marker + r'="[^"]+"[^>]*>', fix, source)


def sub_once(source, old, new):
    if source.count(old) != 1:
        sys.exit(f'Expected exactly one of: {old}')
    return source.replace(old, new)


en = replace_content(html, 'data-i18n', escape_text)
en = replace_content(en, 'data-i18n-html', lambda v: v)
en = replace_attribute(en, 'data-i18n-aria', 'aria-label')
en = replace_attribute(en, 'data-i18n-content', 'content')

# The page itself: language, addresses, the switch's pressed button.
en = sub_once(en, '<html lang="cs">', '<html lang="en">')
en = sub_once(en, '<link rel="canonical" href="https://tomandes.eu/">', f'<link rel="canonical" href="{SITE}/en/">')
en = sub_once(en, '<meta property="og:url" content="https://tomandes.eu/">', f'<meta property="og:url" content="{SITE}/en/">')
en = sub_once(en, '<meta property="og:locale" content="cs_CZ">', '<meta property="og:locale" content="en_US">\n  <meta property="og:locale:alternate" content="cs_CZ">')
en = re.sub(r'<meta property="og:description" content="[^"]*">',
            f'<meta property="og:description" content="{escape_attr(EN["ogDescription"])}">', en, count=1)
used.add('ogDescription')
en = sub_once(en, '<button type="button" data-lang="cs" aria-pressed="true">', '<button type="button" data-lang="cs" aria-pressed="false">')
en = sub_once(en, '<button type="button" data-lang="en" aria-pressed="false">', '<button type="button" data-lang="en" aria-pressed="true">')

# Relative paths (style.css, screenshots/, report/...) now start one folder deeper.
en = re.sub(r'(\s(?:src|href)=")(?![a-z]+:|/|#|\.\./)([^"]+")', r'\1../\2', en)

unused = set(EN) - used
if unused:
    sys.exit(f'English texts no element uses: {sorted(unused)}')

(ROOT / 'en').mkdir(exist_ok=True)
en = sub_once(en, '<!DOCTYPE html>\n',
              '<!DOCTYPE html>\n<!-- Generated by tools/build-en.py from index.html and i18n/en.json - edit those, not this. -->\n')
(ROOT / 'en' / 'index.html').write_text(en, encoding='utf-8', newline='\n')
print(f'en/index.html: {len(used)} texts')
